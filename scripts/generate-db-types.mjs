#!/usr/bin/env node
/**
 * Regenera packages/db/src/types.generated.ts a partir del schema live de Supabase.
 *
 * Opción recomendada (MCP): pide a Claude Code con el MCP `supabase-fyzon` conectado
 * que llame a `generate_typescript_types` y escriba el output aquí. Este script queda
 * como documentación del destino y como fallback CLI.
 *
 * Opción CLI (fallback):
 *   1) pnpm add -g supabase
 *   2) supabase login
 *   3) supabase gen types typescript --project-id ppujrqxiizgfqclbuxet --schema public > packages/db/src/types.generated.ts
 */
import { execSync } from 'node:child_process';
import { writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const outPath = join(__dirname, '..', 'packages', 'db', 'src', 'types.generated.ts');
const projectId = process.env.SUPABASE_PROJECT_ID ?? 'ppujrqxiizgfqclbuxet';

function hasSupabaseCli() {
  try {
    execSync('supabase --version', { stdio: 'ignore' });
    return true;
  } catch {
    return false;
  }
}

function run() {
  if (!hasSupabaseCli()) {
    console.error(
      '[generate-db-types] supabase CLI no detectada.\n' +
        'Instala con: pnpm add -g supabase && supabase login\n' +
        'O pide a Claude Code (con MCP supabase-fyzon) que invoque generate_typescript_types y escriba a:\n' +
        `  ${outPath}`,
    );
    process.exit(1);
  }

  console.log(`[generate-db-types] Generando tipos para project ${projectId}...`);
  const output = execSync(
    `supabase gen types typescript --project-id ${projectId} --schema public`,
    { encoding: 'utf-8' },
  );

  const banner = `// Auto-generated by scripts/generate-db-types.mjs at ${new Date().toISOString()}\n// Do not edit manually.\n\n`;
  writeFileSync(outPath, banner + output, 'utf-8');
  console.log(`[generate-db-types] OK → ${outPath} (${output.length} chars)`);
}

run();
